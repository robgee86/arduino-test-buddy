//go:build unix

package host

import (
	"os/exec"
	"syscall"
)

// endWithChildren makes a cancel end the command together with the processes it started, which share a process group of their own.
func endWithChildren(cmd *exec.Cmd) {
	cmd.SysProcAttr = &syscall.SysProcAttr{Setpgid: true}
	cmd.Cancel = func() error { return syscall.Kill(-cmd.Process.Pid, syscall.SIGKILL) }
}
